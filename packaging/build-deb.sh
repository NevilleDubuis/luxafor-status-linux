#!/usr/bin/env bash
# Builds the luxafor-status .deb package.
#
# Usage: packaging/build-deb.sh [VERSION] [OUTPUT_DIR]
#   VERSION     defaults to the latest git tag (without the leading "v"),
#               or 0.0.0~dev when there is none
#   OUTPUT_DIR  defaults to dist/
#
# Environment:
#   BINARY      the program to package (default: target/release/luxafor-status
#               — run "cargo build --release" first)
#   ARCH        Debian architecture (default: this machine's)
#   MAINTAINER  "Name <email>", overrides the package maintainer
#
# Needs dpkg-deb, dpkg-shlibdeps and gzip (no debhelper).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PKG=luxafor-status
HOMEPAGE="https://github.com/NevilleDubuis/luxafor-status-linux"
MAINTAINER="${MAINTAINER:-Néville Dubuis <ndubuis@gmail.com>}"

VERSION="${1:-}"
if [ -z "$VERSION" ]; then
    VERSION="$(git -C "$ROOT" describe --tags --abbrev=0 2>/dev/null || true)"
    VERSION="${VERSION#v}"
    VERSION="${VERSION:-0.0.0~dev}"
fi
VERSION="${VERSION#v}"
# Pre-releases: semver "0.3.0-beta.1" becomes Debian "0.3.0~beta.1". In a
# Debian version, "-" starts a packaging revision, and "~" sorts before
# anything, so the final 0.3.0 is seen as newer than its betas.
VERSION="${VERSION/-/\~}"
[[ "$VERSION" =~ ^[0-9][A-Za-z0-9.+~-]*$ ]] || { echo "Invalid version: $VERSION" >&2; exit 2; }
OUT="${2:-$ROOT/dist}"
BINARY="${BINARY:-$ROOT/target/release/luxafor-status}"
[ -x "$BINARY" ] || { echo "No $BINARY — run: cargo build --release" >&2; exit 1; }
BINARY="$(realpath "$BINARY")"
ARCH="${ARCH:-$(dpkg --print-architecture)}"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
STAGE="$WORK/${PKG}_${VERSION}_$ARCH"
DOC="$STAGE/usr/share/doc/$PKG"

# --- files ---------------------------------------------------------------------
install -d "$STAGE/DEBIAN" "$STAGE/usr/bin" "$DOC" \
    "$STAGE/usr/share/$PKG" "$STAGE/usr/share/applications" \
    "$STAGE/usr/share/icons/hicolor/scalable/apps" \
    "$STAGE/usr/lib/udev/rules.d" "$STAGE/etc/xdg/autostart" \
    "$STAGE/usr/share/man/man1" "$STAGE/usr/share/metainfo"

# One program; the v1 command names are links to it.
install -m 0755 "$BINARY" "$STAGE/usr/bin/luxafor-status"
for cmd in luxafor-light luxafor-toggle luxafor-tray luxafor-callwatch luxafor-panel; do
    ln -s luxafor-status "$STAGE/usr/bin/$cmd"
done
install -m 0644 "$ROOT/share/statuses.conf" "$STAGE/usr/share/$PKG/statuses.conf"
install -m 0644 "$ROOT/share/icons/luxafor-status.svg" \
    "$STAGE/usr/share/icons/hicolor/scalable/apps/luxafor-status.svg"
install -m 0644 "$ROOT/udev/70-luxafor-status.rules" "$STAGE/usr/lib/udev/rules.d/"
sed "s|@BINDIR@|/usr/bin|g" "$ROOT/share/applications/luxafor-tray.desktop.in" \
    > "$STAGE/etc/xdg/autostart/luxafor-tray.desktop"
sed "s|@BINDIR@|/usr/bin|g" "$ROOT/share/applications/luxafor-panel.desktop.in" \
    > "$STAGE/usr/share/applications/luxafor-panel.desktop"
# AppStream metadata: declares the supported USB IDs (modalias), so software
# centers can suggest this package when a Luxafor light is plugged in.
sed "s|  </provides>|  </provides>\n  <releases>\n    <release version=\"$VERSION\" date=\"$(date -u +%Y-%m-%d)\"/>\n  </releases>|" \
    "$ROOT/packaging/io.github.nevilledubuis.luxafor_status.metainfo.xml" \
    > "$STAGE/usr/share/metainfo/io.github.nevilledubuis.luxafor_status.metainfo.xml"
for page in "$ROOT"/packaging/man/*.1; do
    gzip -9n < "$page" > "$STAGE/usr/share/man/man1/${page##*/}.gz"
done

# Dock launcher for the default statuses, generated by the program itself
# so it always matches what --reload writes. Users who customize their
# statuses get their own copy in ~/.local/share/applications, which takes
# precedence over this one.
GEN="$WORK/gen"
mkdir -p "$GEN"
HOME="$GEN" XDG_DATA_HOME="$GEN/data" XDG_CONFIG_HOME="$GEN/config" \
    XDG_DATA_DIRS="$STAGE/usr/share" PATH="/usr/bin:/bin" LC_ALL=C \
    DBUS_SESSION_BUS_ADDRESS=disabled: \
    "$STAGE/usr/bin/luxafor-status" toggle --reload >/dev/null
sed "s|$STAGE/usr/bin|/usr/bin|g; s|$BINARY|/usr/bin/luxafor-status|g" "$GEN/data/applications/luxafor.desktop" \
    > "$STAGE/usr/share/applications/luxafor.desktop"
chmod 0644 "$STAGE/usr/share/applications/luxafor.desktop"

# --- documentation ---------------------------------------------------------------
install -m 0644 "$ROOT/README.md" "$DOC/README.md"
{
    echo "Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/"
    echo "Upstream-Name: luxafor-status-linux"
    echo "Source: $HOMEPAGE"
    echo
    echo "Files: *"
    echo "Copyright: $(sed -n 's/^Copyright (c) //p' "$ROOT/LICENSE")"
    echo "License: MIT"
    sed -n '/^Permission is hereby granted/,$p' "$ROOT/LICENSE" \
        | sed 's/^$/./; s/^/ /'
} > "$DOC/copyright"
{
    echo "$PKG ($VERSION) unstable; urgency=medium"
    echo
    echo "  * Release $VERSION."
    echo "    See $HOMEPAGE/releases"
    echo
    echo " -- $MAINTAINER  $(LC_ALL=C date -R)"
} | gzip -9n > "$DOC/changelog.gz"

# --- package metadata ----------------------------------------------------------
# Libraries the program links to…
mkdir -p "$WORK/debian"
echo "Source: $PKG" > "$WORK/debian/control"
SHLIBS="$(cd "$WORK" && dpkg-shlibdeps -O "$STAGE/usr/bin/luxafor-status" 2>/dev/null \
    | sed -n 's/^shlibs:Depends=//p')"
# …and those it loads while running: the tray icon (AppIndicator), the
# panel window (X11 / Wayland, OpenGL), the call detection (pactl).
RUNTIME="libayatana-appindicator3-1 | libappindicator3-1, libegl1, libgl1, libx11-6, libxcursor1, libxi6, libxrandr2, libxkbcommon-x11-0, libwayland-client0, pulseaudio-utils"
cat > "$STAGE/DEBIAN/control" <<EOF
Package: $PKG
Version: $VERSION
Architecture: $ARCH
Maintainer: $MAINTAINER
Installed-Size: $(du -sk --exclude=DEBIAN "$STAGE" | cut -f1)
Depends: ${SHLIBS:+$SHLIBS, }$RUNTIME
Recommends: xdg-utils
Section: utils
Priority: optional
Homepage: $HOMEPAGE
Description: control a Luxafor status light (ORB, Flag) from the desktop
 Sets the color of a Luxafor USB status light from a dock launcher, a
 system tray icon showing the current status, a small panel or the command
 line, and switches it to a chosen status automatically while you are in a
 call or while the screen is locked.
 .
 Statuses (name, color, blinking) are configurable per user, and can be set
 for a while (timers). The light is driven directly through its USB HID
 protocol, with no extra driver; a udev rule gives the logged-in user
 access to it without sudo.
EOF

printf '%s\n' /etc/xdg/autostart/luxafor-tray.desktop > "$STAGE/DEBIAN/conffiles"

# v1 started the call detection on its own at login; the tray does it now:
# remove v1's autostart file, unless it was changed (then keep it aside).
# (By hand: dpkg-maintscript-helper doesn't follow the package from
# "all" to an architecture.)
cat > "$STAGE/DEBIAN/preinst" <<'EOF'
#!/bin/sh
set -e
OLD=/etc/xdg/autostart/luxafor-callwatch.desktop
if [ "$1" = "upgrade" ] && dpkg --compare-versions "$2" lt 2.0.0~ && [ -e "$OLD" ]; then
    want="$(dpkg-query -W -f='${Conffiles}\n' luxafor-status 2>/dev/null | awk -v f="$OLD" '$1 == f { print $2 }')"
    if [ "$(md5sum < "$OLD" | cut -d' ' -f1)" = "$want" ]; then
        rm -f "$OLD"
    else
        mv -f "$OLD" "$OLD.dpkg-bak"
    fi
fi
EOF
cat > "$STAGE/DEBIAN/postinst" <<'EOF'
#!/bin/sh
set -e
# Apply the udev rule to a light that is already plugged in.
if [ "$1" = "configure" ] && command -v udevadm >/dev/null 2>&1; then
    udevadm control --reload-rules || true
    udevadm trigger --subsystem-match=hidraw --action=add || true
fi
EOF
cat > "$STAGE/DEBIAN/postrm" <<'EOF'
#!/bin/sh
set -e
if [ "$1" = "remove" ] || [ "$1" = "purge" ]; then
    if command -v udevadm >/dev/null 2>&1; then
        udevadm control --reload-rules || true
    fi
fi
if [ "$1" = "purge" ]; then
    rm -f /etc/xdg/autostart/luxafor-callwatch.desktop.dpkg-bak
fi
EOF
chmod 0755 "$STAGE/DEBIAN/preinst" "$STAGE/DEBIAN/postinst" "$STAGE/DEBIAN/postrm"

# --- build -----------------------------------------------------------------------
mkdir -p "$OUT"
DEB="$OUT/${PKG}_${VERSION}_$ARCH.deb"
dpkg-deb --root-owner-group -Zxz --build "$STAGE" "$DEB" >/dev/null
echo "$DEB"
