//! Desktop notifications ("Busy", "Timer ended — Available"…).

/// Shows a short notification; `icon` is an icon name or an image path.
/// Errors (no notification service) are ignored.
#[cfg(target_os = "linux")]
pub fn notify(text: &str, icon: &str, title: &str) {
    use gtk::gio;
    use gtk::glib::{self, variant::ToVariant};

    let Ok(bus) = gio::bus_get_sync(gio::BusType::Session, gio::Cancellable::NONE) else {
        return;
    };
    let hints = glib::VariantDict::new(None);
    let args = glib::Variant::tuple_from_iter([
        "Luxafor".to_variant(),
        0u32.to_variant(),
        icon.to_variant(),
        title.to_variant(),
        text.to_variant(),
        Vec::<String>::new().to_variant(),
        hints.end(),
        1500i32.to_variant(),
    ]);
    let _ = bus.call_sync(
        Some("org.freedesktop.Notifications"),
        "/org/freedesktop/Notifications",
        "org.freedesktop.Notifications",
        "Notify",
        Some(&args),
        None,
        gio::DBusCallFlags::NONE,
        2000,
        gio::Cancellable::NONE,
    );
}

#[cfg(not(target_os = "linux"))]
pub fn notify(_text: &str, _icon: &str, _title: &str) {
    // Windows: shown by the tray icon (balloon) — see tray.
}

/// The notification icon of a status (generated by `luxafor-toggle --reload`).
pub fn status_icon(id: &str) -> String {
    let path = crate::paths::icon_dir().join(format!("luxafor-{id}.svg"));
    if path.is_file() {
        path.to_string_lossy().into_owned()
    } else {
        "luxafor-status".into()
    }
}
